CREATE TABLE admin_accounts (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    granted_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE admin_accounts IS '관리자 역할. 운영자가 직접 부여·회수한다';

CREATE TABLE admin_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    admin_user_id bigint NOT NULL REFERENCES users(id),
    category varchar(10) NOT NULL CHECK (category IN ('CHANGE', 'ACCESS')),
    action varchar(50) NOT NULL,
    target_type varchar(30) NOT NULL,
    target_id varchar(255) NOT NULL,
    reason varchar(500),
    before_state jsonb,
    after_state jsonb,
    request_id varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_admin_audit_reason CHECK (
        (category = 'CHANGE' AND reason IS NOT NULL AND length(btrim(reason)) > 0)
        OR (category = 'ACCESS' AND reason IS NULL)
    )
);
COMMENT ON TABLE admin_audit_logs IS '관리자 변경·개인정보 접속 기록. 영구 보존';
CREATE INDEX idx_admin_audit_logs_created ON admin_audit_logs (created_at DESC, id DESC);
CREATE INDEX idx_admin_audit_logs_admin ON admin_audit_logs (admin_user_id, created_at DESC);
CREATE INDEX idx_admin_audit_logs_target ON admin_audit_logs (target_type, target_id, created_at DESC);
