ALTER TABLE credit_transactions DROP CONSTRAINT ck_credit_transactions_reason;
ALTER TABLE credit_transactions ADD CONSTRAINT ck_credit_transactions_reason CHECK (
    reason IN ('SIGNUP_REWARD', 'INVITE_REWARD', 'ATTENDANCE_REWARD', 'STORY_CREATION', 'CHAT_TURN', 'CHAT_IMAGE',
               'REFUND', 'PURCHASE', 'EXPIRE', 'PURCHASE_REVERSAL', 'ADMIN_GRANT', 'ADMIN_REVOKE')
);

CREATE TABLE credit_admin_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key varchar(64) NOT NULL,
    admin_user_id bigint NOT NULL REFERENCES users(id),
    user_id bigint NOT NULL REFERENCES users(id),
    type varchar(10) NOT NULL CHECK (type IN ('GRANT', 'REVOKE')),
    requested_amount bigint NOT NULL CHECK (requested_amount > 0),
    applied_amount bigint NOT NULL CHECK (applied_amount >= 0),
    shortfall bigint NOT NULL CHECK (shortfall >= 0),
    balance_after bigint NOT NULL,
    expires_in_days integer,
    expires_at timestamptz,
    transaction_id bigint REFERENCES credit_transactions(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_credit_admin_adjustments_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_credit_admin_adjustments_grant_days CHECK (type <> 'GRANT' OR expires_in_days IS NOT NULL)
);
CREATE INDEX idx_credit_admin_adjustments_user ON credit_admin_adjustments(user_id, created_at DESC);
