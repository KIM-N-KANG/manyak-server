CREATE TABLE push_delivery_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id VARCHAR(255) NOT NULL UNIQUE,
    type VARCHAR(40) NOT NULL,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('SERVICE', 'MARKETING')),
    campaign_id BIGINT REFERENCES push_campaigns(id),
    user_id BIGINT REFERENCES users(id),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('DELIVERED', 'UNDELIVERED', 'DISCARDED')),
    reason VARCHAR(40) NOT NULL,
    delivered_devices INTEGER NOT NULL CHECK (delivered_devices >= 0),
    failed_devices INTEGER NOT NULL CHECK (failed_devices >= 0),
    completed_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_push_delivery_results_campaign ON push_delivery_results(campaign_id) WHERE campaign_id IS NOT NULL;
CREATE INDEX idx_push_delivery_results_type_completed ON push_delivery_results(type, completed_at);
