CREATE TABLE notices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    title varchar(100) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 100),
    body text NOT NULL CHECK (length(body) BETWEEN 1 AND 5000 AND length(btrim(body)) > 0),
    status varchar(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED')),
    published_at timestamptz,
    notified_at timestamptz,
    created_by_user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_notices_published_at CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL)
);
COMMENT ON TABLE notices IS '공지 초안과 게시. 알림 요청한 공지는 삭제하지 않는다';
CREATE INDEX idx_notices_published ON notices (published_at DESC, id DESC) WHERE status = 'PUBLISHED';
CREATE INDEX idx_notices_created ON notices (created_at DESC, id DESC);
ALTER TABLE push_campaigns ADD COLUMN notice_id bigint REFERENCES notices(id);
ALTER TABLE push_campaigns ADD CONSTRAINT uq_push_campaigns_notice UNIQUE (notice_id);
