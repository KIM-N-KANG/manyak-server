CREATE TABLE story_chat_summaries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL REFERENCES story_chats(id),
    through_turn integer NOT NULL CHECK (through_turn >= 1),
    summary text NOT NULL,
    invalidated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_story_chat_summaries_valid ON story_chat_summaries(chat_id, through_turn)
    WHERE invalidated_at IS NULL;
CREATE INDEX idx_story_chat_summaries_chat ON story_chat_summaries(chat_id, through_turn DESC);

INSERT INTO story_chat_summaries(chat_id, through_turn, summary)
SELECT id, summary_through_turn, summary FROM story_chats
WHERE summary_through_turn > 0 AND summary IS NOT NULL;

ALTER TABLE story_chats ADD COLUMN revision integer NOT NULL DEFAULT 0 CHECK (revision >= 0);
