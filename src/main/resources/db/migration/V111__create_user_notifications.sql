CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_key VARCHAR(255) NOT NULL,
    type VARCHAR(40) NOT NULL CHECK (type IN ('STORY_COMPLETED', 'STORY_MODERATION_COMPLETED', 'NOTICE', 'ATTENDANCE_REMINDER', 'PROMOTION')),
    category VARCHAR(16) NOT NULL CHECK (category IN ('NEWS', 'ACTIVITY')),
    title VARCHAR(120) NOT NULL,
    body VARCHAR(300) NOT NULL,
    deep_link VARCHAR(512),
    story_public_id UUID,
    notice_public_id UUID,
    notice_tag VARCHAR(16) CHECK (notice_tag IN ('SERVICE', 'UPDATE', 'MAINTENANCE', 'EVENT', 'PROMOTION')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ,
    CONSTRAINT uk_user_notifications_user_message UNIQUE (user_id, message_key)
);
CREATE INDEX idx_user_notifications_user_created ON user_notifications(user_id, created_at DESC, id DESC);
CREATE INDEX idx_user_notifications_user_category_created ON user_notifications(user_id, category, created_at DESC, id DESC);
CREATE INDEX idx_user_notifications_unread ON user_notifications(user_id, category) WHERE read_at IS NULL;
